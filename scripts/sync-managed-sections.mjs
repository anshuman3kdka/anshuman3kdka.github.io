import fs from 'node:fs/promises';
import path from 'node:path';
import yaml from 'js-yaml';

const repoRoot = process.cwd();
const siteDataPath = path.join(repoRoot, '_data', 'site.yml');
const managedDir = path.join(repoRoot, 'managed_sections');
const marker = '<!-- managed-section: autogenerated -->';

function slugify(value) {
  return String(value || '')
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function toYamlFrontmatter(section) {
  const frontmatter = {
    title: section.title,
    description: section.description || '',
    seo_title: section.seo_title || '',
    og_image: section.og_image || '',
    canonical_url: section.canonical_url || '',
    noindex: Boolean(section.noindex),
    featured_image: section.featured_image || '',
    draft: section.draft !== undefined ? Boolean(section.draft) : false,
    featured: Boolean(section.featured),
    featured_rank: section.featured_rank || '',
    publish_date: section.publish_date || '',
    eyebrow: section.eyebrow || '',
    permalink: `/${section.slug}/`
  };

  const cleaned = Object.fromEntries(
    Object.entries(frontmatter).filter(([, value]) => value !== '')
  );

  return yaml.dump(cleaned, { lineWidth: 0 }).trim();
}

function buildFile(section) {
  const body = (section.body || '').trim();
  return `---\n${toYamlFrontmatter(section)}\n---\n${marker}\n\n${body}\n`;
}

async function ensureDirectory(dirPath) {
  await fs.mkdir(dirPath, { recursive: true });
}

async function readYaml(filePath) {
  const raw = await fs.readFile(filePath, 'utf8');
  return yaml.load(raw) || {};
}

async function main() {
  const siteData = await readYaml(siteDataPath);
  const configuredSections = Array.isArray(siteData.managed_sections) ? siteData.managed_sections : [];
  const normalizedSections = [];
  const seenSlugs = new Set();

  for (const [index, rawSection] of configuredSections.entries()) {
    const title = String(rawSection?.title || rawSection?.label || '').trim();
    const slug = slugify(rawSection?.slug || title);

    if (!title || !slug || seenSlugs.has(slug)) {
      continue;
    }

    seenSlugs.add(slug);
    normalizedSections.push({
      title,
      slug,
      description: rawSection?.description || '',
      seo_title: rawSection?.seo_title || '',
      og_image: rawSection?.og_image || '',
      canonical_url: rawSection?.canonical_url || '',
      noindex: rawSection?.noindex || false,
      featured_image: rawSection?.featured_image || '',
      draft: rawSection?.draft || false,
      featured: rawSection?.featured || false,
      featured_rank: rawSection?.featured_rank || '',
      publish_date: rawSection?.publish_date || '',
      eyebrow: rawSection?.eyebrow || '',
      body: rawSection?.body || `Write your ${title} page content here.`,
      index
    });
  }

  siteData.header_links = Array.isArray(siteData.header_links) ? siteData.header_links : [];
  const nonManagedHeaderLinks = siteData.header_links.filter((link) => !link?.managed_section);

  for (const section of normalizedSections) {
    nonManagedHeaderLinks.push({
      label: section.title,
      url: `/${section.slug}/`,
      managed_section: true,
      managed_slug: section.slug
    });
  }

  siteData.header_links = nonManagedHeaderLinks;
  await fs.writeFile(siteDataPath, yaml.dump(siteData, { lineWidth: 0 }), 'utf8');

  await ensureDirectory(managedDir);
  const existingFiles = await fs.readdir(managedDir);
  const wantedFiles = new Set();

  for (const section of normalizedSections) {
    const fileName = `${section.slug}.md`;
    wantedFiles.add(fileName);
    await fs.writeFile(path.join(managedDir, fileName), buildFile(section), 'utf8');
  }

  for (const fileName of existingFiles) {
    if (!fileName.endsWith('.md') || wantedFiles.has(fileName)) {
      continue;
    }

    const filePath = path.join(managedDir, fileName);
    const raw = await fs.readFile(filePath, 'utf8');
    if (raw.includes(marker)) {
      await fs.unlink(filePath);
    }
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
